#!/bin/sh
# Build the static pages and copy them into the Next.js app (one folder up).
set -e
cd "$(dirname "$0")"
R="$(cd .. && pwd)"
node build.mjs > build-report.json
rm -rf "$R/public/site" "$R/public/assets"
cp -r out/public/. "$R/public/"
node -e "const r=require('./out/rewrites.json');require('fs').writeFileSync('$R/site-rewrites.mjs','// Generated by site-src/sync.sh. Clean URLs map to the pre-rendered pages in public/site.\nexport default '+JSON.stringify(r,null,1)+';\n')"
echo synced
